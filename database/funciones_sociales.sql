CREATE TABLE IF NOT EXISTS EventoExtra (
 id_evento INT PRIMARY KEY, cupo INT NULL, radio_m INT NOT NULL DEFAULT 500,
 visibilidad VARCHAR(10) NOT NULL DEFAULT 'publico', codigo VARCHAR(32) UNIQUE,
 ciudad VARCHAR(100) NOT NULL DEFAULT '',
 recurrencia VARCHAR(10) NOT NULL DEFAULT 'ninguna', cancelado TINYINT NOT NULL DEFAULT 0,
 FOREIGN KEY (id_evento) REFERENCES Evento(id_evento) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS PerfilExtra (
 id_usuario INT PRIMARY KEY, bio VARCHAR(300) NOT NULL DEFAULT '', intereses VARCHAR(500) NOT NULL DEFAULT '',
 comentarios TINYINT NOT NULL DEFAULT 1, recordatorios TINYINT NOT NULL DEFAULT 1,
 cambios TINYINT NOT NULL DEFAULT 1, social TINYINT NOT NULL DEFAULT 1, correo TINYINT NOT NULL DEFAULT 0,
 FOREIGN KEY (id_usuario) REFERENCES Usuario(id_usuario) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS Participacion (
 id_usuario INT NOT NULL, id_evento INT NOT NULL, estado VARCHAR(15) NOT NULL,
 actualizado TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP(6), PRIMARY KEY(id_usuario,id_evento),
 FOREIGN KEY(id_usuario) REFERENCES Usuario(id_usuario) ON DELETE CASCADE,
 FOREIGN KEY(id_evento) REFERENCES Evento(id_evento) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS Asistencia (
 id_usuario INT NOT NULL, id_evento INT NOT NULL, distancia_m INT NOT NULL,
 fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY(id_usuario,id_evento),
 FOREIGN KEY(id_usuario) REFERENCES Usuario(id_usuario) ON DELETE CASCADE,
 FOREIGN KEY(id_evento) REFERENCES Evento(id_evento) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS Comentario (
 id INT AUTO_INCREMENT PRIMARY KEY, id_usuario INT NOT NULL, id_evento INT NOT NULL,
 texto VARCHAR(1000) NOT NULL, visible TINYINT NOT NULL DEFAULT 1, fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(id_usuario) REFERENCES Usuario(id_usuario) ON DELETE CASCADE,
 FOREIGN KEY(id_evento) REFERENCES Evento(id_evento) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS Valoracion (
 id_usuario INT NOT NULL, id_evento INT NOT NULL, estrellas TINYINT NOT NULL,
 PRIMARY KEY(id_usuario,id_evento), CHECK(estrellas BETWEEN 1 AND 5),
 FOREIGN KEY(id_usuario) REFERENCES Usuario(id_usuario) ON DELETE CASCADE,
 FOREIGN KEY(id_evento) REFERENCES Evento(id_evento) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS Colaborador (
 id_usuario INT NOT NULL, id_evento INT NOT NULL, PRIMARY KEY(id_usuario,id_evento),
 FOREIGN KEY(id_usuario) REFERENCES Usuario(id_usuario) ON DELETE CASCADE,
 FOREIGN KEY(id_evento) REFERENCES Evento(id_evento) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS Invitacion (
 id_usuario INT NOT NULL, id_evento INT NOT NULL, PRIMARY KEY(id_usuario,id_evento),
 FOREIGN KEY(id_usuario) REFERENCES Usuario(id_usuario) ON DELETE CASCADE,
 FOREIGN KEY(id_evento) REFERENCES Evento(id_evento) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ListaEvento (
 id INT AUTO_INCREMENT PRIMARY KEY, id_usuario INT NOT NULL, nombre VARCHAR(100) NOT NULL,
 publica TINYINT NOT NULL DEFAULT 0, token VARCHAR(48) NOT NULL UNIQUE,
 FOREIGN KEY(id_usuario) REFERENCES Usuario(id_usuario) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ListaItem (
 id_lista INT NOT NULL, id_evento INT NOT NULL, PRIMARY KEY(id_lista,id_evento),
 FOREIGN KEY(id_lista) REFERENCES ListaEvento(id) ON DELETE CASCADE,
 FOREIGN KEY(id_evento) REFERENCES Evento(id_evento) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS Notificacion (
 id INT AUTO_INCREMENT PRIMARY KEY, id_usuario INT NOT NULL, tipo VARCHAR(30) NOT NULL,
 texto VARCHAR(500) NOT NULL, id_evento INT NULL, leida TINYINT NOT NULL DEFAULT 0,
 clave VARCHAR(100) NULL UNIQUE, fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(id_usuario) REFERENCES Usuario(id_usuario) ON DELETE CASCADE,
 FOREIGN KEY(id_evento) REFERENCES Evento(id_evento) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS CorreoPendiente (
 id INT AUTO_INCREMENT PRIMARY KEY, id_usuario INT NOT NULL, texto VARCHAR(500) NOT NULL,
 estado VARCHAR(15) NOT NULL DEFAULT 'pendiente', fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(id_usuario) REFERENCES Usuario(id_usuario) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS FotoEvento (
 id INT AUTO_INCREMENT PRIMARY KEY, id_evento INT NOT NULL, id_usuario INT NOT NULL,
 imagen VARCHAR(255) NOT NULL, descripcion VARCHAR(180) NOT NULL DEFAULT '',
 visible TINYINT NOT NULL DEFAULT 1, fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(id_usuario) REFERENCES Usuario(id_usuario) ON DELETE CASCADE,
 FOREIGN KEY(id_evento) REFERENCES Evento(id_evento) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS RelacionUsuario (
 origen INT NOT NULL, destino INT NOT NULL, tipo VARCHAR(10) NOT NULL,
 PRIMARY KEY(origen,destino,tipo), CHECK(origen <> destino),
 FOREIGN KEY(origen) REFERENCES Usuario(id_usuario) ON DELETE CASCADE,
 FOREIGN KEY(destino) REFERENCES Usuario(id_usuario) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS Reporte (
 id INT AUTO_INCREMENT PRIMARY KEY, id_usuario INT NOT NULL, tipo VARCHAR(15) NOT NULL,
 destino INT NOT NULL, motivo VARCHAR(500) NOT NULL, estado VARCHAR(15) NOT NULL DEFAULT 'abierto',
 fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(id_usuario) REFERENCES Usuario(id_usuario) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS Grupo (
 id INT AUTO_INCREMENT PRIMARY KEY, id_usuario INT NOT NULL, nombre VARCHAR(100) NOT NULL,
 descripcion VARCHAR(300) NOT NULL DEFAULT '', codigo VARCHAR(20) NOT NULL UNIQUE,
 FOREIGN KEY(id_usuario) REFERENCES Usuario(id_usuario) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS MiembroGrupo (
 id_grupo INT NOT NULL, id_usuario INT NOT NULL, PRIMARY KEY(id_grupo,id_usuario),
 FOREIGN KEY(id_grupo) REFERENCES Grupo(id) ON DELETE CASCADE,
 FOREIGN KEY(id_usuario) REFERENCES Usuario(id_usuario) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS GrupoEvento (
 id_grupo INT NOT NULL, id_evento INT NOT NULL, PRIMARY KEY(id_grupo,id_evento),
 FOREIGN KEY(id_grupo) REFERENCES Grupo(id) ON DELETE CASCADE,
 FOREIGN KEY(id_evento) REFERENCES Evento(id_evento) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS Cupon (
 id INT AUTO_INCREMENT PRIMARY KEY, id_evento INT NOT NULL, codigo VARCHAR(30) NOT NULL,
 descuento INT NOT NULL, max_usos INT NULL, usos INT NOT NULL DEFAULT 0, vence DATETIME NULL,
 UNIQUE(id_evento,codigo), CHECK(descuento BETWEEN 1 AND 100),
 FOREIGN KEY(id_evento) REFERENCES Evento(id_evento) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS Entrada (
 id INT AUTO_INCREMENT PRIMARY KEY, id_usuario INT NOT NULL, id_evento INT NOT NULL,
 token VARCHAR(64) NOT NULL UNIQUE, importe DECIMAL(10,2) NOT NULL,
 modo VARCHAR(15) NOT NULL DEFAULT 'demostracion', usada DATETIME NULL,
 fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP, UNIQUE(id_usuario,id_evento),
 FOREIGN KEY(id_usuario) REFERENCES Usuario(id_usuario) ON DELETE CASCADE,
 FOREIGN KEY(id_evento) REFERENCES Evento(id_evento) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS VisitaEvento (
 id_evento INT NOT NULL, visitante VARCHAR(64) NOT NULL, id_usuario INT NULL, dia DATE NOT NULL,
 PRIMARY KEY(id_evento,visitante,dia),
 FOREIGN KEY(id_evento) REFERENCES Evento(id_evento) ON DELETE CASCADE,
 FOREIGN KEY(id_usuario) REFERENCES Usuario(id_usuario) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
